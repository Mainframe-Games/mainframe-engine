#!/bin/sh
# Shader tooling shared by the justfile and CI. POSIX sh; needs glslc + spirv-val for compile.
#
#   build/shaders.sh compile [OUT_DIR]   compile every shader to SPIR-V (Vulkan 1.2) and spirv-val it;
#                                        writes next to the source, or mirrors the tree under OUT_DIR
#   build/shaders.sh lock                rewrite the lock file from the current sources and .spv files
#   build/shaders.sh check               fail if any source or .spv no longer matches the lock
#                                        (a source edited without recompiling, or an uncommitted .spv)
#   build/shaders.sh list                print the shader sources considered
#
# Shaders: MainframeEngine/Content/Shaders/**/*.vk.{vert,frag,comp} (engine, compiled with
# -I MainframeEngine/Content/Shaders/include exactly like the MSBuild CompileShaders target in
# build/Shaders.targets) and Examples/SilkVulkanExamples/Content/Shaders/**/*.{vert,frag,comp}. The engine's
# shared includes (include/*.glsl, incl. the generated limits.glsl) are locked too: editing one makes every
# engine .spv stale until recompiled.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
LOCK="MainframeEngine/Content/Shaders/shaders.lock"
TARGET_ENV="vulkan1.2"
ENGINE_SHADERS="MainframeEngine/Content/Shaders"
INCLUDE_DIR="$ENGINE_SHADERS/include"

cd "$ROOT"

list_sources() {
    {
        find "$ENGINE_SHADERS" -type f \
            \( -name '*.vk.vert' -o -name '*.vk.frag' -o -name '*.vk.comp' \)
        find Examples/SilkVulkanExamples/Content/Shaders -type f \
            \( -name '*.vert' -o -name '*.frag' -o -name '*.comp' \)
    } | LC_ALL=C sort
}

list_includes() {
    find "$INCLUDE_DIR" -type f -name '*.glsl' | LC_ALL=C sort
}

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

require() {
    command -v "$1" >/dev/null 2>&1 || { echo "error: '$1' not found on PATH (install the Vulkan SDK or glslc/spirv-tools)" >&2; exit 2; }
}

compile() {
    require glslc
    require spirv-val
    out_dir=${1:-}
    count=0
    for src in $(list_sources); do
        if [ -n "$out_dir" ]; then
            spv="$out_dir/$src.spv"
            mkdir -p "$(dirname "$spv")"
        else
            spv="$src.spv"
        fi
        glslc --target-env="$TARGET_ENV" -I "$INCLUDE_DIR" "$src" -o "$spv"
        spirv-val --target-env "$TARGET_ENV" "$spv"
        count=$((count + 1))
    done
    echo "Compiled and validated $count shaders (target $TARGET_ENV)${out_dir:+ into $out_dir}."
}

write_lock() {
    tmp="$LOCK.tmp"
    {
        echo "# Generated by build/shaders.sh lock — do not edit. <source sha256> <spv sha256> <source>"
        for src in $(list_sources); do
            if [ ! -f "$src.spv" ]; then
                echo "error: $src.spv is missing; run build/shaders.sh compile" >&2
                rm -f "$tmp"
                exit 1
            fi
            echo "$(sha256 "$src") $(sha256 "$src.spv") $src"
        done
        for inc in $(list_includes); do
            echo "$(sha256 "$inc") - $inc"
        done
    } > "$tmp"
    mv "$tmp" "$LOCK"
    echo "Wrote $LOCK ($(grep -vc '^#' "$LOCK") shaders)."
}

check_lock() {
    [ -f "$LOCK" ] || { echo "error: $LOCK is missing; run 'just shaders'" >&2; exit 1; }
    failed=0
    for src in $(list_sources); do
        line=$(grep " $src\$" "$LOCK" || true)
        if [ -z "$line" ]; then
            echo "stale: $src is not in $LOCK" >&2
            failed=1
            continue
        fi
        want_src=$(echo "$line" | cut -d' ' -f1)
        want_spv=$(echo "$line" | cut -d' ' -f2)
        if [ "$(sha256 "$src")" != "$want_src" ]; then
            echo "stale: $src changed since its .spv was compiled" >&2
            failed=1
        fi
        if [ ! -f "$src.spv" ] || [ "$(sha256 "$src.spv")" != "$want_spv" ]; then
            echo "stale: $src.spv does not match $LOCK" >&2
            failed=1
        fi
    done
    for inc in $(list_includes); do
        line=$(grep " $inc\$" "$LOCK" || true)
        if [ -z "$line" ] || [ "$(sha256 "$inc")" != "$(echo "$line" | cut -d' ' -f1)" ]; then
            echo "stale: include $inc changed (or is new) since the shaders were compiled" >&2
            failed=1
        fi
    done
    for locked in $(grep -v '^#' "$LOCK" | cut -d' ' -f3); do
        [ -f "$locked" ] || { echo "stale: $locked is in $LOCK but no longer exists" >&2; failed=1; }
    done
    if [ "$failed" -ne 0 ]; then
        echo "Shader lock check failed: run 'just shaders' and commit the .spv files and $LOCK." >&2
        exit 1
    fi
    echo "Shader lock OK ($(grep -vc '^#' "$LOCK") shaders)."
}

case "${1:-}" in
    compile) compile "${2:-}" ;;
    lock) write_lock ;;
    check) check_lock ;;
    list) list_sources; list_includes ;;
    *) sed -n '2,12p' "$0" >&2; exit 2 ;;
esac
