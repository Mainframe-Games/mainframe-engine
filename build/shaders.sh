#!/bin/sh
# Shader tooling shared by the justfile and CI. POSIX sh; needs slangc + spirv-val for compile (ADR 0144).
#
#   build/shaders.sh compile [OUT_DIR]   compile every shader to SPIR-V (Vulkan 1.2) and spirv-val it;
#                                        writes X.vk.<stage>.spv next to X.vk.<stage>.slang, or mirrors the tree
#                                        under OUT_DIR
#   build/shaders.sh lock                rewrite the lock file from the current sources and .spv files
#   build/shaders.sh check               fail if any source or .spv no longer matches the lock
#                                        (a source edited without recompiling, or an uncommitted .spv)
#   build/shaders.sh list                print the shader sources considered
#
# Shaders: MainframeEngine/Content/Shaders/**/*.vk.{vert,frag,comp}.slang (engine, compiled with the flags of the
# MSBuild CompileShaders target in build/Shaders.targets: -target spirv -capability spirv_1_5 -matrix-layout-row-major
# -entry main -stage <stage> -I MainframeEngine/Content/Shaders/include). The engine's shared includes
# (include/*.slang, incl. the generated limits.slang) are locked too: editing one makes every engine .spv stale until
# recompiled.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
LOCK="MainframeEngine/Content/Shaders/shaders.lock"
TARGET_ENV="vulkan1.2"
ENGINE_SHADERS="MainframeEngine/Content/Shaders"
INCLUDE_DIR="$ENGINE_SHADERS/include"

cd "$ROOT"

list_sources() {
    find "$ENGINE_SHADERS" -type f \
        \( -name '*.vk.vert.slang' -o -name '*.vk.frag.slang' -o -name '*.vk.comp.slang' \) | LC_ALL=C sort
}

list_includes() {
    find "$INCLUDE_DIR" -type f -name '*.slang' | LC_ALL=C sort
}

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

# X.vk.frag.slang -> X.vk.frag.spv
spv_of() {
    echo "${1%.slang}.spv"
}

stage_of() {
    case $1 in
        *.vk.vert.slang) echo vertex ;;
        *.vk.frag.slang) echo fragment ;;
        *.vk.comp.slang) echo compute ;;
        *) echo "error: cannot tell the stage of $1" >&2; exit 2 ;;
    esac
}

require() {
    command -v "$1" >/dev/null 2>&1 || { echo "error: '$1' not found on PATH (install the Vulkan SDK, or slangc + spirv-tools)" >&2; exit 2; }
}

slangc_version() {
    slangc -v 2>&1 | head -n 1
}

# The slangc that built the committed .spv, from the lock's second line ("# slangc <version>").
locked_slangc_version() {
    [ -f "$LOCK" ] && sed -n 's/^# slangc //p' "$LOCK" | head -n 1
}

compile() {
    out_dir=${1:-}
    require slangc
    require spirv-val
    version=$(slangc_version)
    # Same minimum as build/Shaders.targets (SlangMinimumVersion): older compilers lack syntax the shaders use.
    major_minor=$(echo "$version" | sed -n 's/^v\{0,1\}\([0-9][0-9]*\)\.\([0-9][0-9]*\).*/\1 \2/p')
    set -- $major_minor
    if [ -z "$major_minor" ] || [ "$1" -lt 2026 ] || { [ "$1" -eq 2026 ] && [ "$2" -lt 1 ]; }; then
        echo "error: slangc '$version' is older than 2026.1 (update the Vulkan SDK or Slang)" >&2
        exit 2
    fi
    locked=$(locked_slangc_version)
    if [ -n "$locked" ] && [ "$locked" != "$version" ]; then
        echo "note: compiling with slangc $version; the committed .spv were built with $locked, so their bytes may change." >&2
    fi
    count=0
    for src in $(list_sources); do
        if [ -n "$out_dir" ]; then
            spv="$out_dir/$(spv_of "$src")"
            mkdir -p "$(dirname "$spv")"
        else
            spv=$(spv_of "$src")
        fi
        slangc "$src" -target spirv -capability spirv_1_5 -matrix-layout-row-major \
            -entry main -stage "$(stage_of "$src")" -I "$INCLUDE_DIR" -o "$spv"
        spirv-val --target-env "$TARGET_ENV" "$spv"
        count=$((count + 1))
    done
    echo "Compiled and validated $count shaders (target $TARGET_ENV)${out_dir:+ into $out_dir}."
}

write_lock() {
    tmp="$LOCK.tmp"
    {
        echo "# Generated by build/shaders.sh lock — do not edit. <source sha256> <spv sha256> <source>"
        echo "# slangc $(slangc_version)"
        for src in $(list_sources); do
            if [ ! -f "$(spv_of "$src")" ]; then
                echo "error: $(spv_of "$src") is missing; run build/shaders.sh compile" >&2
                rm -f "$tmp"
                exit 1
            fi
            echo "$(sha256 "$src") $(sha256 "$(spv_of "$src")") $src"
        done
        for inc in $(list_includes); do
            echo "$(sha256 "$inc") - $inc"
        done
    } > "$tmp"
    mv "$tmp" "$LOCK"
    echo "Wrote $LOCK ($(grep -vc '^#' "$LOCK") shaders)."
}

check_lock() {
    [ -f "$LOCK" ] || { echo "error: $LOCK is missing; run 'just shaders'" >&2; exit 1; }
    failed=0
    for src in $(list_sources); do
        line=$(grep " $src\$" "$LOCK" || true)
        if [ -z "$line" ]; then
            echo "stale: $src is not in $LOCK" >&2
            failed=1
            continue
        fi
        want_src=$(echo "$line" | cut -d' ' -f1)
        want_spv=$(echo "$line" | cut -d' ' -f2)
        if [ "$(sha256 "$src")" != "$want_src" ]; then
            echo "stale: $src changed since its .spv was compiled" >&2
            failed=1
        fi
        spv=$(spv_of "$src")
        if [ ! -f "$spv" ] || [ "$(sha256 "$spv")" != "$want_spv" ]; then
            echo "stale: $spv does not match $LOCK" >&2
            failed=1
        fi
    done
    for inc in $(list_includes); do
        line=$(grep " $inc\$" "$LOCK" || true)
        if [ -z "$line" ] || [ "$(sha256 "$inc")" != "$(echo "$line" | cut -d' ' -f1)" ]; then
            echo "stale: include $inc changed (or is new) since the shaders were compiled" >&2
            failed=1
        fi
    done
    for locked in $(grep -v '^#' "$LOCK" | cut -d' ' -f3); do
        [ -f "$locked" ] || { echo "stale: $locked is in $LOCK but no longer exists" >&2; failed=1; }
    done
    if [ "$failed" -ne 0 ]; then
        echo "Shader lock check failed: run 'just shaders' and commit the .spv files and $LOCK." >&2
        exit 1
    fi
    echo "Shader lock OK ($(grep -vc '^#' "$LOCK") shaders)."
}

case "${1:-}" in
    compile) compile "${2:-}" ;;
    lock) write_lock ;;
    check) check_lock ;;
    list) list_sources; list_includes ;;
    *) sed -n '2,16p' "$0" >&2; exit 2 ;;
esac
