using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using System.Xml.Linq;

namespace MainframeEngine.Tests.Project;

/// <summary>
/// G19 phase 4 (ADR 0259) pieces a JIT test process can check: the macOS bundle base directory of a NativeAOT executable,
/// and the rd.xml that gives Facepunch.Steamworks' structs their marshalling data under NativeAOT, kept in sync with the
/// vendored assemblies.
/// </summary>
public sealed class NativeAotTests : IDisposable
{
    private readonly string _folder = Directory.CreateTempSubdirectory("mf-aot").FullName;

    public void Dispose() => Directory.Delete(_folder, recursive: true);

    [Fact]
    public void ANativeExecutableInABundleUsesItsMonoBundleFolder()
    {
        var contents = Path.Combine(_folder, "Game.app", "Contents");
        var macOs = Path.Combine(contents, "MacOS");
        Directory.CreateDirectory(macOs);
        Assert.Null(NativeAppBundle.BaseDirectoryFor(macOs)); // no MonoBundle: not a release bundle

        Directory.CreateDirectory(Path.Combine(contents, NativeAppBundle.AppDirectory));
        Assert.Equal(Path.Combine(contents, "MonoBundle") + Path.DirectorySeparatorChar, NativeAppBundle.BaseDirectoryFor(macOs));
        Assert.Equal(Path.Combine(contents, "MonoBundle") + Path.DirectorySeparatorChar, NativeAppBundle.BaseDirectoryFor(macOs + Path.DirectorySeparatorChar));
        Assert.Null(NativeAppBundle.BaseDirectoryFor(Path.Combine(contents, "MonoBundle")));
        Assert.Null(NativeAppBundle.BaseDirectoryFor(_folder));
        Assert.Null(NativeAppBundle.BaseDirectoryFor(null));
        Assert.Null(NativeAppBundle.Apply()); // a JIT process changes nothing
    }

    public static TheoryData<string> FacepunchBuilds => new() { "Posix", "Win64" };

    /// <summary>
    /// build/steamworks/Facepunch.Steamworks.&lt;build&gt;.rd.xml asks ILC for the structure marshalling of every struct
    /// Facepunch can marshal (MainframeGame.props adds it to NativeAOT publishes). A Facepunch upgrade changes its structs:
    /// run this test with <c>MAINFRAME_UPDATE_RDXML=1</c> to rewrite the files.
    /// </summary>
    [Theory]
    [MemberData(nameof(FacepunchBuilds))]
    public void TheSteamworksRdXmlListsEveryFacepunchStruct(string build)
    {
        var repo = RepoRoot();
        var assembly = Assembly.LoadFile(Path.Combine(repo, "Plugins", "Facepunch.Steamworks", $"Facepunch.Steamworks.{build}.dll"));
        var expected = RdXml(assembly);
        var file = Path.Combine(repo, "build", "steamworks", $"Facepunch.Steamworks.{build}.rd.xml");
        if (Environment.GetEnvironmentVariable("MAINFRAME_UPDATE_RDXML") == "1")
            File.WriteAllText(file, expected);
        Assert.Equal(expected, File.ReadAllText(file).ReplaceLineEndings("\n"));
        var document = XDocument.Parse(expected);
        Assert.Contains(document.Descendants(), e => (string?)e.Attribute("Name") == "Steamworks.Data.PersonaStateChange_t"); // blittable: failed without it
        Assert.DoesNotContain(document.Descendants(), e => (string?)e.Attribute("Name") == "Steamworks.Data.P2Packet"); // a managed byte[]: not marshallable
    }

    private static string RdXml(Assembly assembly)
    {
        Type[] types;
        try
        {
            types = assembly.GetTypes();
        }
        catch (ReflectionTypeLoadException e)
        {
            types = [.. e.Types.OfType<Type>()];
        }

        var names = types.Where(t => t.IsValueType && !t.IsEnum && !t.ContainsGenericParameters && !Generated(t) && Marshallable(t, 0))
            .Select(t => t.FullName!).Order(StringComparer.Ordinal);
        var name = assembly.GetName().Name;
        var text = new StringBuilder();
        text.Append("<!-- Generated by NativeAotTests.TheSteamworksRdXmlListsEveryFacepunchStruct (MAINFRAME_UPDATE_RDXML=1): every marshallable struct of ")
            .Append(name).Append(". See build/MainframeGame.props. -->\n");
        text.Append("<Directives xmlns=\"http://schemas.microsoft.com/netfx/2013/01/metadata\">\n  <Application>\n    <Assembly Name=\"").Append(name).Append("\">\n");
        foreach (var type in names)
            text.Append("      <Type Name=\"").Append(type).Append("\" MarshalStructure=\"Required All\" />\n");
        text.Append("    </Assembly>\n  </Application>\n</Directives>\n");
        return text.ToString();
    }

    // Marshallable: every reference-type field says how ([MarshalAs]); struct fields are marshallable themselves.
    private static bool Marshallable(Type type, int depth)
    {
        if (depth > 8)
            return false;
        foreach (var field in type.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic))
        {
            var fieldType = field.FieldType;
            if (!fieldType.IsValueType)
            {
                if (field.GetCustomAttribute<System.Runtime.InteropServices.MarshalAsAttribute>() is null)
                    return false;
                continue;
            }

            if (!fieldType.IsPrimitive && !fieldType.IsEnum && fieldType != typeof(IntPtr) && fieldType != typeof(UIntPtr) && !Marshallable(fieldType, depth + 1))
                return false;
        }

        return true;
    }

    private static bool Generated(Type? type)
    {
        for (; type is not null; type = type.DeclaringType)
            if (type.Name.Contains('<', StringComparison.Ordinal) || type.GetCustomAttribute<CompilerGeneratedAttribute>() is not null)
                return true;
        return false;
    }

    private static string RepoRoot([CallerFilePath] string here = "")
    {
        for (var directory = Path.GetDirectoryName(here); directory is not null; directory = Path.GetDirectoryName(directory))
            if (File.Exists(Path.Combine(directory, "MainframeEngine.slnx")))
                return directory;
        throw new DirectoryNotFoundException("MainframeEngine.slnx not found above " + here);
    }
}
