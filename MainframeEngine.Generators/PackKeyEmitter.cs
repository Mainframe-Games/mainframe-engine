using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;

namespace MainframeEngine.Generators;

/// <summary>
/// Compiles an export's pack key into the game assembly (G19 phase 3, ADR 0240): a <c>[ModuleInitializer]</c> calls
/// <c>PackKeys.Register(masked, mask)</c>, where the mask is SHA-256 of the assembly's name, so neither the key's bytes nor
/// its base64 appear in the assembly, and the same key gives the same assembly (reproducible builds). This is deterrence,
/// not secrecy: the key ships in the game. NativeAOT (phase 4) leaves it in machine code instead of IL.
/// </summary>
internal static class PackKeyEmitter
{
    private const int KeySize = 32;

    public static void Emit(SourceProductionContext context, string base64, string assemblyName)
    {
        if (base64.Length == 0)
            return;
        byte[] key;
        try
        {
            key = Convert.FromBase64String(base64);
        }
        catch (FormatException)
        {
            key = [];
        }

        if (key.Length != KeySize)
        {
            context.ReportDiagnostic(Diagnostic.Create(Diagnostics.InvalidPackKey, Location.None));
            return;
        }

        byte[] mask;
        using (var sha = SHA256.Create())
            mask = sha.ComputeHash(Encoding.UTF8.GetBytes("MainframePackKey:" + assemblyName));
        var masked = new byte[KeySize];
        for (var i = 0; i < KeySize; i++)
            masked[i] = (byte)(key[i] ^ mask[i]);

        var source = new StringBuilder()
            .AppendLine("// <auto-generated/> G19: this export's pack key, masked (mf-export -p:MainframePackKey).")
            .AppendLine("namespace MainframeEngine.Generated")
            .AppendLine("{")
            .AppendLine("    internal static class PackKeyRegistration")
            .AppendLine("    {")
            .AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]")
            .AppendLine("        internal static void Register() => global::MainframeEngine.PackKeys.Register(")
            .Append("            new byte[] { ").Append(Bytes(masked)).AppendLine(" },")
            .Append("            new byte[] { ").Append(Bytes(mask)).AppendLine(" });")
            .AppendLine("    }")
            .AppendLine("}");
        context.AddSource("MainframeEngine.PackKey.g.cs", source.ToString());
    }

    private static string Bytes(byte[] bytes)
    {
        var text = new StringBuilder(bytes.Length * 6);
        for (var i = 0; i < bytes.Length; i++)
            text.Append(i == 0 ? "" : ", ").Append("0x").Append(bytes[i].ToString("x2", System.Globalization.CultureInfo.InvariantCulture));
        return text.ToString();
    }
}
